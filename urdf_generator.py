def deep_merge(base: dict[str, Any], override: dict[str, Any] | None) -> dict[str, Any]:
    result = copy.deepcopy(base)
    if override is None:
        return result
    if not isinstance(override, dict):
        raise ValueError("The top-level YAML value must be a map.")
    for key, value in override.items():
        if key in result and isinstance(result[key], dict) and isinstance(value, dict):
            result[key] = deep_merge(result[key], value)
        else:
            result[key] = value
    return result


def load_config(config_path: str | Path) -> dict[str, Any]:
    with open(config_path, "r", encoding="utf-8") as stream:
        return deep_merge(DEFAULT_CONFIG, yaml.safe_load(stream))


def bool_enabled(section: dict[str, Any], default: bool = True) -> bool:
    return bool(section.get("enabled", default))


def inertia_box(mass: float, x: float, y: float, z: float) -> str:
    return (
        f'ixx="{mass * (y * y + z * z) / 12.0:.6f}" ixy="0" ixz="0" '
        f'iyy="{mass * (x * x + z * z) / 12.0:.6f}" iyz="0" '
        f'izz="{mass * (x * x + y * y) / 12.0:.6f}"'
    )


